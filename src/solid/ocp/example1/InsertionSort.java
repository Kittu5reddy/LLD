package solid.ocp.example1;

public class InsertionSort implements Sort{
    @Override
    public int[] sort(int[] arr) {

        System.out.printf("Insertion Sort");
        int n = arr.length;
        for (int i = 1; i < n; ++i) {
            int key = arr[i];
            int j = i - 1;

            while (j >= 0 && arr[j] > key) {
                arr[j + 1] = arr[j];
                j = j - 1;
            }
            arr[j + 1] = key;
        }
        return arr;
    }

}
